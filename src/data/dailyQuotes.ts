/**
 * คำนวณหา Quote ประจำวันโดยใช้ Date string (YYYY-MM-DD)
 * เพื่อให้ทุกคนได้ข้อความไม่ซ้ำกันในแต่ละวันโดยอัตโนมัติ
 */
export function getDailyQuote(dateStr?: string): QuoteItem {
  const dateKey = dateStr || new Date().toISOString().split("T")[0];
  
  // Simple deterministic hash based on YYYY-MM-DD
  let hash = 0;
  for (let i = 0; i < dateKey.length; i++) {
    hash = (hash * 31 + dateKey.charCodeAt(i)) >>> 0;
  }
  
  const index = hash % DAILY_QUOTES.length;
  return DAILY_QUOTES[index];
}

/**
 * คำนวณหา Preset ฉากหลังประจำวันตาม Date string
 */
export function getDailyBackground(dateStr?: string): BackgroundItem {
  const dateKey = dateStr || new Date().toISOString().split("T")[0];
  let hash = 0;
  for (let i = 0; i < dateKey.length; i++) {
    hash = (hash * 17 + dateKey.charCodeAt(i)) >>> 0;
  }
  const index = hash % BACKGROUND_PRESETS.length;
  return BACKGROUND_PRESETS[index];
}
