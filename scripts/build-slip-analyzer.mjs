// Bundles src/mobile/lib/slipAnalyzer.ts into a self-contained script that
// native Swift code evaluates with JavaScriptCore (exposes `SlipAnalyzer`).
// Run `npm run build:slip-analyzer` after changing slip parsing rules;
// slipAnalyzerBundle.test.ts fails while the committed bundle is stale.
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

export const SLIP_ANALYZER_BUNDLE_PATH = `${root}ios/SlipKit/slip-analyzer.js`;

export async function buildSlipAnalyzer() {
  const result = await build({
    entryPoints: [`${root}src/mobile/lib/slipAnalyzer.ts`],
    bundle: true,
    write: false,
    format: "iife",
    globalName: "SlipAnalyzer",
    target: "es2020",
    platform: "neutral",
    legalComments: "none",
    banner: { js: "// GENERATED by scripts/build-slip-analyzer.mjs - do not edit." },
  });
  return result.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(SLIP_ANALYZER_BUNDLE_PATH, await buildSlipAnalyzer());
  console.log(`wrote ${SLIP_ANALYZER_BUNDLE_PATH}`);
}
